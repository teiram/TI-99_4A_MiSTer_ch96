`timescale 1ns/1ps

// psram_bridge -- TI-99/4A calibrated APS6404L PSRAM front end.
//
// The legacy TI core expects a small, fixed-latency 16-bit SDRAM:
//   addr[25:0] byte address, wtbt[1:0] byte enables / 8-bit lane mode,
//   rd/we level strobes, ready/dout handshake.
//
// This bridge keeps that port in clk_ref (clk_sys), but moves all real PSRAM
// traffic into clk (clk_ram / SCLK). A single outstanding host request is
// latched on the rd/we rising edge and handed to the PSRAM scheduler through
// conservative toggle synchronisers. The result is returned through a second
// toggle handshake and registered back into clk_ref before `ready` rises.
//
// One 8 MiB chip covers every TI address currently generated by the core:
//   psram_addr = addr[22:0]; addr[25:23] are ignored.
// The second chip is left idle.
//
// Calibration uses the proven Amstrad/C64 psram.sv + psram_cal3.sv +
// psram_dps.sv stack with CHIPS=1. While cal_busy is high the calibrator owns
// the PSRAM host port and core traffic is held off by the top-level reset.

module psram_bridge #(
    parameter integer S          = 20,             // phase steps per HALF period: 4*Fvco/Fout
    parameter [22:0]  CAL_BASE   = 23'h700000,     // scratch outside all TI mappings
    parameter [4:0]   DPS_CNTL   = 5'd2,           // logical counter of outclk_2
    parameter         DPS_DIRUP  = 1'b1,
    parameter integer OP_TMO     = 16384,
    parameter integer PWRUP_CYCLES = 30000,
    parameter integer RST_CYCLES   = 4000,
    parameter integer MID_CYCLES   = 100,
    parameter integer CAL_WORDS    = 16,
    parameter integer CAL_PASSES   = 4
) (
    // ---- physical PSRAM pads, chip 1 ----
    output              PSRAM_SCLK,
    output              PSRAM_CE_N,
    output        [3:0] PSRAM_SIO_OUT,
    output        [3:0] PSRAM_SIO_OE,
    input         [3:0] PSRAM_SIO_IN,

    // ---- physical PSRAM pads, chip 2 (unused) ----
    output              PSRAM2_SCLK,
    output              PSRAM2_CE_N,
    output        [3:0] PSRAM2_SIO_OUT,
    output        [3:0] PSRAM2_SIO_OE,
    input         [3:0] PSRAM2_SIO_IN,

    // ---- clocks / calibration plumbing ----
    input               init,            // held while the PLL is unlocked
    input               clk,             // clk_ram: fabric clock and SCLK pad
    input               clk_ref,         // clk_sys: host side of this bridge
    input               clk_cap,         // phase-shifted capture clock (outclk_2)
    input               scanclk,         // PLL reference for DPS
    input               pll_phase_done,
    output              pll_phase_en,
    output              pll_updn,
    output        [4:0] pll_cntsel,
    output              cal_done,
    output              cal_fail,
    output              cal_busy,
    output       [63:0] cal_status,
    output              cal_ready,       // cal_done synchronised into clk_ref

    // ---- core-facing SDRAM-compatible port (clk_ref domain) ----
    input         [25:0] addr,
    input         [15:0] din,
    output        [15:0] dout,
    input         [1:0]  wtbt,
    input                rd,
    input                we,
    output               ready,
    output               busy
);

    assign PSRAM_SCLK = clk;

    // Single-chip build: keep the second device deselected and its outputs
    // released. The input port is unused but present for top-level symmetry.
    assign PSRAM2_SCLK    = 1'b0;
    assign PSRAM2_CE_N    = 1'b1;
    assign PSRAM2_SIO_OUT = 4'h0;
    assign PSRAM2_SIO_OE  = 4'h0;

    wire rst_n = ~init;

    // ======================================================================
    // PSRAM controller + shared calibration
    // ======================================================================
    wire        p_ready;
    wire [15:0] p_dout;
    reg  [22:0] p_addr;
    reg  [1:0]  p_wtbt;
    reg  [15:0] p_din;
    reg         p_rd, p_we;

    wire [22:0] cal_addr;
    wire [1:0]  cal_wtbt;
    wire [15:0] cal_din;
    wire        cal_rd1, cal_we1;
    wire        cal_rd2, cal_we2;
    wire [2:0]  cal_c;

    psram #(
        .PWRUP_CYCLES(PWRUP_CYCLES),
        .RST_CYCLES  (RST_CYCLES),
        .MID_CYCLES  (MID_CYCLES),
        .LEAN        (1)
    ) psram_i (
        .clk    (clk),
        .reset  (init),
        .init   (init),

        .ce_n   (PSRAM_CE_N),
        .sio_out(PSRAM_SIO_OUT),
        .sio_oe (PSRAM_SIO_OE),
        .sio_in (PSRAM_SIO_IN),

        .clk_cap(clk_cap),
        .cap_sel(cal_c),

        .ready  (p_ready),
        .addr   (cal_busy ? cal_addr : p_addr),
        .wtbt   (cal_busy ? cal_wtbt : p_wtbt),
        .rd     (cal_busy ? cal_rd1  : p_rd),
        .we     (cal_busy ? cal_we1  : p_we),
        .din    (cal_busy ? cal_din  : p_din),
        .dout   (p_dout)
    );

    reg clk_det = 1'b0;
    always @(posedge clk_cap) clk_det <= clk;

    wire dps_phase_en, dps_updn;
    wire dps_req_tgl, dps_req_up, dps_done_tgl, dps_err;

    psram_cal3 #(
        .CHIPS    (1),
        .BASE_ADDR(CAL_BASE),
        .N_WORDS  (CAL_WORDS),
        .PASSES   (CAL_PASSES),
        .S        (S),
        .DEF_C    (3'd3)
    ) cal (
        .clk        (clk),
        .rst_n      (rst_n),
        .recal      (1'b0),

        .ready1     (p_ready),
        .dout1      (p_dout),
        .rd1        (cal_rd1),
        .we1        (cal_we1),

        .ready2     (1'b1),
        .dout2      (16'h0000),
        .rd2        (cal_rd2),
        .we2        (cal_we2),

        .addr       (cal_addr),
        .wtbt       (cal_wtbt),
        .din        (cal_din),
        .cap_c      (cal_c),

        .dps_req_tgl(dps_req_tgl),
        .dps_req_up (dps_req_up),
        .dps_done_tgl(dps_done_tgl),
        .dps_err    (dps_err),
        .clk_det    (clk_det),

        .busy       (cal_busy),
        .done       (cal_done),
        .fail       (cal_fail),
        .status     (cal_status)
    );

    psram_dps #(
        .CNTSEL (DPS_CNTL),
        .DIR_UP (DPS_DIRUP)
    ) dps (
        .scanclk    (scanclk),
        .rst_n      (rst_n),
        .req_tgl    (dps_req_tgl),
        .req_up     (dps_req_up),
        .done_tgl   (dps_done_tgl),
        .err        (dps_err),
        .phase_en   (dps_phase_en),
        .updn       (dps_updn),
        .cntsel     (pll_cntsel),
        .phase_done (pll_phase_done)
    );

    assign pll_phase_en = dps_phase_en;
    assign pll_updn     = dps_updn;

    // ======================================================================
    // clk_ref domain: latch one host request, publish one result
    // ======================================================================
    reg cd0 = 1'b0, cd1 = 1'b0;
    always @(posedge clk_ref) begin
        cd0 <= cal_done;
        cd1 <= cd0;
    end
    assign cal_ready = cd1;

    reg cb0 = 1'b0, cb1 = 1'b0;
    always @(posedge clk_ref) begin
        cb0 <= cal_busy;
        cb1 <= cb0;
    end

    reg [2:0] rq = 3'd0;        // req_tgl synchroniser into clk
    reg [2:0] rs = 3'd0;        // res_tgl synchroniser into clk_ref
    reg       res_seen = 1'b0;

    reg old_rd = 1'b0, old_we = 1'b0;
    reg        host_req = 1'b0;
    reg        req_tgl = 1'b0;
    reg        host_we = 1'b0;
    reg  [1:0] host_wtbt = 2'b00;
    reg  [25:0] host_addr = 26'd0;
    reg  [15:0] host_din = 16'd0;

    reg  [15:0] host_dout = 16'hFFFF;

    wire res_pending = (rs[2] != res_seen);

    assign dout  = host_dout;
    assign ready = cal_ready && !init && !host_req && !res_pending;
    assign busy  = cb1 || host_req || res_pending;

    always @(posedge clk_ref) begin
        if (init) begin
            rq         <= 3'd0;
            rs         <= 3'd0;
            res_seen   <= 1'b0;
            old_rd     <= 1'b0;
            old_we     <= 1'b0;
            host_req   <= 1'b0;
            req_tgl    <= 1'b0;
            host_we    <= 1'b0;
            host_wtbt  <= 2'b00;
            host_addr  <= 26'd0;
            host_din   <= 16'd0;
            host_dout  <= 16'hFFFF;
        end else begin
            rq <= {rq[1:0], req_tgl};
            rs <= {rs[1:0], res_tgl};

            old_rd <= rd;
            old_we <= we;

            // One outstanding request: the top level gates loader/erase
            // traffic with ioctl_wait, and the CPU has 31 wait states.
            if (!host_req && ((~old_rd & rd) || (~old_we & we))) begin
                host_we   <= we;
                host_wtbt <= wtbt;
                host_addr <= addr;
                host_din  <= din;
                req_tgl   <= ~req_tgl;
                host_req  <= 1'b1;
            end

            if (res_pending) begin
                if (host_req) begin
                    if (!host_we) host_dout <= res_data;
                    host_req <= 1'b0;
                end
                res_seen <= rs[2];
            end
        end
    end

    // ======================================================================
    // clk domain: PSRAM scheduler
    // ======================================================================
    reg        req_seen = 1'b0;
    wire       req_change = (rq[2] != req_seen);

    reg        res_tgl = 1'b0;
    reg  [15:0] res_data = 16'h0000;

    reg  [25:0] e_addr;
    reg  [15:0] e_din;
    reg  [1:0]  e_wtbt;
    reg         e_we;
    reg  [15:0] etmo;

    localparam [1:0] E_IDLE = 2'd0, E_RDY = 2'd1, E_LOW = 2'd2, E_HIGH = 2'd3;
    reg [1:0] est;

    always @(posedge clk) begin
        if (init || cal_busy) begin
            req_seen <= 1'b0;
            est      <= E_IDLE;
            etmo     <= 16'd0;
            e_addr   <= 26'd0;
            e_din    <= 16'd0;
            e_wtbt   <= 2'b00;
            e_we     <= 1'b0;
            p_rd     <= 1'b0;
            p_we     <= 1'b0;
            p_addr   <= 23'd0;
            p_wtbt   <= 2'b00;
            p_din    <= 16'd0;
        end else begin
            case (est)
                E_IDLE: begin
                    p_rd <= 1'b0;
                    p_we <= 1'b0;
                    if (req_change) begin
                        req_seen <= rq[2];
                        e_addr   <= host_addr;
                        e_din    <= host_din;
                        e_wtbt   <= host_wtbt;
                        e_we     <= host_we;
                        etmo     <= 16'd0;
                        est      <= E_RDY;
                    end
                end

                // Wait until the controller is idle, then present one strobe.
                E_RDY: begin
                    if (p_ready) begin
                        p_addr <= e_addr[22:0];
                        p_wtbt <= e_wtbt;
                        p_din  <= e_din;
                        p_rd   <= ~e_we;
                        p_we   <= e_we;
                        etmo   <= 16'd0;
                        est    <= E_LOW;
                    end else if (etmo == OP_TMO) begin
                        etmo    <= 16'd0;
                        res_data <= 16'hFFFF;
                        res_tgl  <= ~res_tgl;
                        est      <= E_IDLE;
                    end else etmo <= etmo + 16'd1;
                end

                // The strobe is caught when ready drops.
                E_LOW: begin
                    p_rd <= 1'b0;
                    p_we <= 1'b0;
                    if (!p_ready) begin
                        etmo <= 16'd0;
                        est  <= E_HIGH;
                    end else if (etmo == 16'd31) begin
                        etmo    <= 16'd0;
                        res_data <= 16'hFFFF;
                        res_tgl  <= ~res_tgl;
                        est      <= E_IDLE;
                    end else etmo <= etmo + 16'd1;
                end

                // Wait for the frame to finish and the result to assemble.
                E_HIGH: begin
                    if (p_ready) begin
                        res_data <= e_we ? 16'h0000 : p_dout;
                        res_tgl  <= ~res_tgl;
                        etmo     <= 16'd0;
                        est      <= E_IDLE;
                    end else if (etmo == OP_TMO) begin
                        etmo    <= 16'd0;
                        res_data <= 16'hFFFF;
                        res_tgl  <= ~res_tgl;
                        est      <= E_IDLE;
                    end else etmo <= etmo + 16'd1;
                end

                default: est <= E_IDLE;
            endcase
        end
    end

endmodule
